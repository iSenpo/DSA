void solve()
{
    int n;
    cin >> n;
    vector<int> ans;
    while(n--){
        ans.pb(1);
        int t = 0;
        while(ans.size() >= 2 && ans[ans.size() - 1] == ans[ans.size() - 2]){
            ans.pop_back();
            t = ans.back();
            ans.pop_back();
            ans.push_back(t + 1);
        }
    }
    for(int i : ans){
        cout << i << ' ';
    }
}
